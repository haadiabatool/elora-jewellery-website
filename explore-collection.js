document.addEventListener('DOMContentLoaded', () => {
  const collectionCards = document.querySelectorAll('.collections-grid .card-cta');
  const fullscreenView = document.getElementById('collectionModal');
  const closeBtn = document.getElementById('modalCloseBtn');
  
  const categoryTitle = document.getElementById('modalCategoryTitle');
  const categoryDesc = document.getElementById('modalCategoryDesc');
  const productsGrid = document.getElementById('modalProductsGrid');

  // Open Full-Screen View
  collectionCards.forEach(cardCta => {
    cardCta.addEventListener('click', (e) => {
      e.preventDefault();
      const href = cardCta.getAttribute('href').replace('#', '');
      const data = collectionsData[href];

      if (data) {
        // Set Collection Header Info
        categoryTitle.textContent = data.title;
        categoryDesc.textContent = data.subtitle;

        // Render 10 Unique Product Cards
        productsGrid.innerHTML = data.items.map(item => `
          <div class="fs-product-card">
            <div class="fs-product-media">
              <img src="${item.image}" alt="${item.title}" loading="lazy" onerror="this.src='https://images.unsplash.com/photo-1599643478518-a784e5dc4c8f?auto=format&fit=crop&q=80&w=600'">
            </div>
            <div class="fs-product-details">
              <div>
                <h3 class="fs-product-title">${item.title}</h3>
                <p class="fs-product-desc">${item.desc}</p>
                <div class="fs-product-price">${item.price}</div>
              </div>
              <div class="fs-card-actions">
                <button class="btn-fs-cart" onclick="addToCart('${item.id}', '${item.title}')">Add to Bag</button>
                <button class="btn-fs-order" onclick="orderNow('${item.id}', '${item.title}')">Order Now</button>
              </div>
            </div>
          </div>
        `).join('');

        // Open Fullscreen Overlay & Prevent Body Scroll
        fullscreenView.classList.add('is-open');
        document.body.style.overflow = 'hidden';
      }
    });
  });

  // Close Full-Screen View & Back to Homepage
  closeBtn.addEventListener('click', () => {
    fullscreenView.classList.remove('is-open');
    document.body.style.overflow = '';
  });
});


